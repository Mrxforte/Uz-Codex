enum class GeneratorStage {
    SOURCE_SELECTION,
    CONFIG,
    REVIEW_AND_GENERATE,
    ACTIVE_TEST,
    RESULTS,
    SAVED_HISTORY
}

@OptIn(ExperimentalMaterial3Api::class, ExperimentalLayoutApi::class)
@Composable
fun TestGeneratorScreen(
    repository: LegalRepository,
    onBack: () -> Unit
) {
    val context = LocalContext.current
    val coroutineScope = rememberCoroutineScope()
    val allCodes = remember { repository.getAllCodes() }

    // Navigation & Stage
    var currentStage by remember { mutableStateOf(GeneratorStage.SOURCE_SELECTION) }
    var activeTab by remember { mutableIntStateOf(0) } // 0 = Generator, 1 = Saved History

    // Step 1: Source Selection State
    var selectedCodeIds by remember { mutableStateOf(setOf<String>()) }
    var selectedChapters by remember { mutableStateOf(mapOf<String, Set<String>>()) }
    var selectedArticleIds by remember { mutableStateOf(setOf<String>()) }
    var selectedRanges by remember { mutableStateOf(mapOf<String, List<IntRange>>()) }
    var expandedCodeId by remember { mutableStateOf<String?>(null) }
    var searchQuery by remember { mutableStateOf("") }
    var selectedCategoryFilter by remember { mutableStateOf("Barchasi") }

    val currentSelection = remember(selectedCodeIds, selectedChapters, selectedArticleIds, selectedRanges) {
        LegalSourceSelection(
            selectedCodeIds = selectedCodeIds,
            selectedChapters = selectedChapters,
            selectedArticleIds = selectedArticleIds,
            selectedArticleRanges = selectedRanges
        )
    }
    val resolvedArticles = remember(currentSelection) {
        currentSelection.resolveArticles(context)
    }

    // Step 2: Configuration State
    var questionCountOption by remember { mutableIntStateOf(10) } // 5, 10, 20, 50, 100, 200, -1 = Custom, -2 = Max
    var customQuestionCountText by remember { mutableStateOf("15") }
    var selectedTypes by remember {
        mutableStateOf(
            setOf(QuestionType.SINGLE_CHOICE, QuestionType.SCENARIO_BASED, QuestionType.TRUE_FALSE)
        )
    }
    var selectedDifficulty by remember { mutableStateOf(TestDifficulty.MIXED) }
    var includeExplanations by remember { mutableStateOf(true) }
    var showAnswerImmediately by remember { mutableStateOf(false) }
    var shuffleQuestions by remember { mutableStateOf(true) }
    var excludePreviouslyGenerated by remember { mutableStateOf(true) }
    var includeArticleReferences by remember { mutableStateOf(true) }
    var separateTestPerCode by remember { mutableStateOf(false) }
    var selectedTimeLimitMinutes by remember { mutableStateOf<Int?>(15) }

    val effectiveQuestionCount = remember(questionCountOption, customQuestionCountText) {
        when (questionCountOption) {
            -2 -> Int.MAX_VALUE // Max Available Mode
            -1 -> customQuestionCountText.toIntOrNull()?.coerceIn(1, 200) ?: 10
            else -> questionCountOption
        }
    }

    val currentConfig = remember(
        effectiveQuestionCount, questionCountOption, selectedTypes, selectedDifficulty,
        includeExplanations, showAnswerImmediately, shuffleQuestions, excludePreviouslyGenerated,
        includeArticleReferences, separateTestPerCode, selectedTimeLimitMinutes
    ) {
        TestGenerationConfig(
            questionCount = if (questionCountOption == -2) 500 else effectiveQuestionCount,
            isMaxAvailableMode = (questionCountOption == -2),
            selectedTypes = selectedTypes,
            difficulty = selectedDifficulty,
            includeExplanations = includeExplanations,
            showAnswerImmediately = showAnswerImmediately,
            shuffleQuestionsAndOptions = shuffleQuestions,
            excludePreviouslyGenerated = excludePreviouslyGenerated,
            includeArticleReferences = includeArticleReferences,
            generateSeparateTestsPerCode = separateTestPerCode,
            timeLimitMinutes = selectedTimeLimitMinutes
        )
    }

    // Step 3: Generation & Active Test Session State
    var isGenerating by remember { mutableStateOf(false) }
    var generationProgressText by remember { mutableStateOf("Generatsiya tayyorlanmoqda...") }
    var generationCurrentCount by remember { mutableIntStateOf(0) }
    var generationTargetEstimate by remember { mutableIntStateOf(10) }

    var generatedQuestions by remember { mutableStateOf<List<GeneratedTestQuestion>>(emptyList()) }
    var currentQuestionIndex by remember { mutableIntStateOf(0) }
    var userSingleAnswers by remember { mutableStateOf<Map<Int, Int>>(emptyMap()) } // Single/TF/Scenario
    var userMultipleAnswers by remember { mutableStateOf<Map<Int, Set<Int>>>(emptyMap()) } // Multiple Choice
    var userFillAnswers by remember { mutableStateOf<Map<Int, String>>(emptyMap()) } // Fill in blank
    var confirmedPracticeIndices by remember { mutableStateOf(setOf<Int>()) }

    var secondsRemaining by remember { mutableIntStateOf(900) }
    var isTimerRunning by remember { mutableStateOf(false) }
    var showGridSheet by remember { mutableStateOf(false) }

    // History & Saved Sets
    val savedTestSetsState = repository.getAllSavedTestSets().collectAsState(initial = emptyList())
    val testAttemptsState = repository.getAllTestAttempts().collectAsState(initial = emptyList())

    // Timer Effect
    LaunchedEffect(currentStage, isTimerRunning) {
        if (currentStage == GeneratorStage.ACTIVE_TEST && isTimerRunning && selectedTimeLimitMinutes != null) {
            while (secondsRemaining > 0 && currentStage == GeneratorStage.ACTIVE_TEST) {
                delay(1000L)
                secondsRemaining--
            }
            if (secondsRemaining <= 0 && currentStage == GeneratorStage.ACTIVE_TEST) {
                // Auto finish on time expiration
                currentStage = GeneratorStage.RESULTS
            }
        }
    }

    fun startGenerationJob() {
        if (currentSelection.isEmpty()) return
        isGenerating = true
        currentStage = GeneratorStage.REVIEW_AND_GENERATE

        coroutineScope.launch {
            val questions = repository.generateRagTestQuestions(
                selection = currentSelection,
                config = currentConfig,
                onProgress = { count, target, status ->
                    generationCurrentCount = count
                    generationTargetEstimate = target
                    generationProgressText = status
                }
            )

            isGenerating = false
            generatedQuestions = questions
            currentQuestionIndex = 0
            userSingleAnswers = emptyMap()
            userMultipleAnswers = emptyMap()
            userFillAnswers = emptyMap()
            confirmedPracticeIndices = emptySet()

            selectedTimeLimitMinutes?.let {
                secondsRemaining = it * 60
                isTimerRunning = true
            }

            if (questions.isNotEmpty()) {
                currentStage = GeneratorStage.ACTIVE_TEST
            }
        }
    }

    fun finishTest() {
        isTimerRunning = false
        val total = generatedQuestions.size
        var correct = 0

        generatedQuestions.forEachIndexed { idx, q ->
            when (q.questionType) {
                QuestionType.MULTIPLE_CHOICE -> {
                    val userSet = userMultipleAnswers[idx] ?: emptySet()
                    val correctSet = q.correctIndices.toSet()
                    if (userSet == correctSet) correct++
                }
                QuestionType.FILL_IN_BLANK -> {
                    val userText = userFillAnswers[idx]?.trim()?.lowercase() ?: ""
                    val target = q.fillInBlankAnswer?.trim()?.lowercase() ?: ""
                    if (userText.isNotEmpty() && target.contains(userText)) correct++
                }
                else -> {
                    val userAns = userSingleAnswers[idx]
                    if (userAns != null && q.correctIndices.contains(userAns)) correct++
                }
            }
        }

        val pct = if (total > 0) (correct * 100) / total else 0
        val earnedXp = correct * 10 + (if (pct >= 80) 100 else 0)

        coroutineScope.launch {
            repository.saveTestAttempt(
                testSetId = "rag_gen_${System.currentTimeMillis()}",
                testTitle = currentSelection.getSelectionSummaryText(context),
                scorePercentage = pct,
                correctCount = correct,
                totalCount = total,
                userAnswersMap = userSingleAnswers.mapValues { listOf(it.value) },
                durationSeconds = (selectedTimeLimitMinutes?.times(60) ?: 0) - secondsRemaining,
                earnedXp = earnedXp
            )
        }
        currentStage = GeneratorStage.RESULTS
    }

    Scaffold(
        topBar = {
            UzLegalTopBar(
                title = "SMART RAG Test Generatori",
                subtitle = when (currentStage) {
                    GeneratorStage.SOURCE_SELECTION -> "1-qadam: Manbalarni tanlash (${resolvedArticles.size} ta modda)"
                    GeneratorStage.CONFIG -> "2-qadam: Test parametrlarini sozlash"
                    GeneratorStage.REVIEW_AND_GENERATE -> "3-qadam: Generatsiya jarayoni"
                    GeneratorStage.ACTIVE_TEST -> "Savol ${currentQuestionIndex + 1} / ${generatedQuestions.size}"
                    GeneratorStage.RESULTS -> "Test Natijalari"
                    GeneratorStage.SAVED_HISTORY -> "Saqlangan testlar va tarix"
                },
                showBackButton = true,
                onBackClick = {
                    when (currentStage) {
                        GeneratorStage.SOURCE_SELECTION -> onBack()
                        GeneratorStage.CONFIG -> currentStage = GeneratorStage.SOURCE_SELECTION
                        GeneratorStage.REVIEW_AND_GENERATE -> currentStage = GeneratorStage.CONFIG
                        GeneratorStage.ACTIVE_TEST -> currentStage = GeneratorStage.CONFIG
                        GeneratorStage.RESULTS -> currentStage = GeneratorStage.SOURCE_SELECTION
                        GeneratorStage.SAVED_HISTORY -> currentStage = GeneratorStage.SOURCE_SELECTION
                    }
                },
                actions = {
                    if (currentStage == GeneratorStage.ACTIVE_TEST && selectedTimeLimitMinutes != null) {
                        val minutes = secondsRemaining / 60
                        val seconds = secondsRemaining % 60
                        Surface(
                            color = if (secondsRemaining < 180) UzLegalErrorContainer else UzLegalTealSurface,
                            shape = RoundedCornerShape(16.dp),
                            border = BorderStroke(
                                1.dp,
                                if (secondsRemaining < 180) UzLegalError else UzLegalTealBorder
                            ),
                            modifier = Modifier.padding(end = 8.dp)
                        ) {
                            Row(
                                verticalAlignment = Alignment.CenterVertically,
                                modifier = Modifier.padding(horizontal = 8.dp, vertical = 4.dp)
                            ) {
                                Icon(
                                    imageVector = Icons.Default.Timer,
                                    contentDescription = null,
                                    tint = if (secondsRemaining < 180) UzLegalError else UzLegalTeal,
                                    modifier = Modifier.size(14.dp)
                                )
                                Spacer(modifier = Modifier.width(4.dp))
                                Text(
                                    text = String.format("%02d:%02d", minutes, seconds),
                                    style = MaterialTheme.typography.labelSmall.copy(
                                        color = if (secondsRemaining < 180) UzLegalError else UzLegalNavyHeadings,
                                        fontWeight = FontWeight.Bold
                                    )
                                )
                            }
                        }

                        IconButton(onClick = { showGridSheet = true }) {
                            Icon(imageVector = Icons.Default.GridView, contentDescription = "Savollar kartasi")
                        }
                    }
                }
            )
        }
    ) { innerPadding ->
        Column(
            modifier = Modifier
                .fillMaxSize()
                .padding(innerPadding)
                .background(MaterialTheme.colorScheme.background)
        ) {
            // Main Navigation Header Tabs
            if (currentStage != GeneratorStage.ACTIVE_TEST && currentStage != GeneratorStage.REVIEW_AND_GENERATE) {
                TabRow(
                    selectedTabIndex = activeTab,
                    containerColor = MaterialTheme.colorScheme.surface,
                    contentColor = UzLegalTeal
                ) {
                    Tab(
                        selected = activeTab == 0,
                        onClick = {
                            activeTab = 0
                            if (currentStage == GeneratorStage.SAVED_HISTORY) {
                                currentStage = GeneratorStage.SOURCE_SELECTION
                            }
                        },
                        text = { Text("Test Generatori", fontWeight = FontWeight.Bold) },
                        icon = { Icon(imageVector = Icons.Default.AutoAwesome, contentDescription = null, modifier = Modifier.size(18.dp)) }
                    )
                    Tab(
                        selected = activeTab == 1,
                        onClick = {
                            activeTab = 1
                            currentStage = GeneratorStage.SAVED_HISTORY
                        },
                        text = { Text("Tarix & Saqlanganlar", fontWeight = FontWeight.Bold) },
                        icon = { Icon(imageVector = Icons.Default.History, contentDescription = null, modifier = Modifier.size(18.dp)) }
                    )
                }
            }

            Box(modifier = Modifier.weight(1f)) {
                when (currentStage) {
                    GeneratorStage.SOURCE_SELECTION -> {
                        SourceSelectionContent(
                            allCodes = allCodes,
                            selectedCodeIds = selectedCodeIds,
                            selectedChapters = selectedChapters,
                            selectedArticleIds = selectedArticleIds,
                            searchQuery = searchQuery,
                            onSearchChange = { searchQuery = it },
                            selectedCategory = selectedCategoryFilter,
                            onCategorySelect = { selectedCategoryFilter = it },
                            expandedCodeId = expandedCodeId,
                            onToggleExpand = { codeId ->
                                expandedCodeId = if (expandedCodeId == codeId) null else codeId
                            },
                            onToggleCodeSelect = { codeId ->
                                selectedCodeIds = if (selectedCodeIds.contains(codeId)) {
                                    selectedCodeIds - codeId
                                } else {
                                    selectedCodeIds + codeId
                                }
                            },
                            onSelectAll = {
                                selectedCodeIds = allCodes.map { it.id }.toSet()
                            },
                            onDeselectAll = {
                                selectedCodeIds = emptySet()
                                selectedChapters = emptyMap()
                                selectedArticleIds = emptySet()
                                selectedRanges = emptyMap()
                            },
                            onToggleChapterSelect = { codeId, chapterTitle ->
                                val existing = selectedChapters[codeId] ?: emptySet()
                                val updated = if (existing.contains(chapterTitle)) existing - chapterTitle else existing + chapterTitle
                                selectedChapters = selectedChapters + (codeId to updated)
                            },
                            onToggleArticleSelect = { articleId ->
                                selectedArticleIds = if (selectedArticleIds.contains(articleId)) {
                                    selectedArticleIds - articleId
                                } else {
                                    selectedArticleIds + articleId
                                }
                            },
                            resolvedArticleCount = resolvedArticles.size,
                            onNextConfig = {
                                currentStage = GeneratorStage.CONFIG
                            }
                        )
                    }

                    GeneratorStage.CONFIG -> {
                        TestConfigContent(
                            selectionSummaryText = currentSelection.getSelectionSummaryText(context),
                            resolvedCount = resolvedArticles.size,
                            questionCountOption = questionCountOption,
                            onSelectCountOption = { questionCountOption = it },
                            customText = customQuestionCountText,
                            onCustomTextChange = { customQuestionCountText = it },
                            selectedTypes = selectedTypes,
                            onToggleType = { type ->
                                selectedTypes = if (selectedTypes.contains(type)) selectedTypes - type else selectedTypes + type
                            },
                            difficulty = selectedDifficulty,
                            onSelectDifficulty = { selectedDifficulty = it },
                            includeExplanations = includeExplanations,
                            onToggleExplanations = { includeExplanations = it },
                            showAnswerImmediately = showAnswerImmediately,
                            onToggleShowAnswer = { showAnswerImmediately = it },
                            shuffleQuestions = shuffleQuestions,
                            onToggleShuffle = { shuffleQuestions = it },
                            excludePreviouslyGenerated = excludePreviouslyGenerated,
                            onToggleExcludePrev = { excludePreviouslyGenerated = it },
                            timeLimitMinutes = selectedTimeLimitMinutes,
                            onSelectTimeLimit = { selectedTimeLimitMinutes = it },
                            onStartGenerate = { startGenerationJob() }
                        )
                    }

                    GeneratorStage.REVIEW_AND_GENERATE -> {
                        GenerationProgressContent(
                            isGenerating = isGenerating,
                            currentCount = generationCurrentCount,
                            targetCount = generationTargetEstimate,
                            statusText = generationProgressText,
                            onCancel = {
                                isGenerating = false
                                currentStage = GeneratorStage.CONFIG
                            }
                        )
                    }

                    GeneratorStage.ACTIVE_TEST -> {
                        val q = generatedQuestions.getOrNull(currentQuestionIndex)
                        if (q != null) {
                            ActiveTestContent(
                                question = q,
                                currentIndex = currentQuestionIndex,
                                totalCount = generatedQuestions.size,
                                userSingleAnswer = userSingleAnswers[currentQuestionIndex],
                                userMultipleAnswers = userMultipleAnswers[currentQuestionIndex] ?: emptySet(),
                                userFillAnswer = userFillAnswers[currentQuestionIndex] ?: "",
                                showAnswerImmediately = showAnswerImmediately,
                                isConfirmedPractice = confirmedPracticeIndices.contains(currentQuestionIndex),
                                onSelectSingle = { optIdx ->
                                    userSingleAnswers = userSingleAnswers + (currentQuestionIndex to optIdx)
                                },
                                onToggleMultiple = { optIdx ->
                                    val currentSet = userMultipleAnswers[currentQuestionIndex] ?: emptySet()
                                    val newSet = if (currentSet.contains(optIdx)) currentSet - optIdx else currentSet + optIdx
                                    userMultipleAnswers = userMultipleAnswers + (currentQuestionIndex to newSet)
                                },
                                onFillChange = { text ->
                                    userFillAnswers = userFillAnswers + (currentQuestionIndex to text)
                                },
                                onConfirmPractice = {
                                    confirmedPracticeIndices = confirmedPracticeIndices + currentQuestionIndex
                                },
                                onPrev = { if (currentQuestionIndex > 0) currentQuestionIndex-- },
                                onNext = {
                                    if (currentQuestionIndex < generatedQuestions.size - 1) {
                                        currentQuestionIndex++
                                    } else finishTest()
                                },
                                onFinish = { finishTest() }
                            )
                        }
                    }

                    GeneratorStage.RESULTS -> {
                        TestResultsContent(
                            questions = generatedQuestions,
                            userSingleAnswers = userSingleAnswers,
                            onRetake = { startGenerationJob() },
                            onNewTest = { currentStage = GeneratorStage.SOURCE_SELECTION }
                        )
                    }

                    GeneratorStage.SAVED_HISTORY -> {
                        SavedHistoryContent(
                            savedSets = savedTestSetsState.value,
                            attempts = testAttemptsState.value,
                            onLaunchSavedSet = { setEntity ->
                                coroutineScope.launch {
                                    val qList = repository.getQuestionsForTestSet(setEntity.id)
                                    if (qList.isNotEmpty()) {
                                        generatedQuestions = qList
                                        currentQuestionIndex = 0
                                        userSingleAnswers = emptyMap()
                                        userMultipleAnswers = emptyMap()
                                        userFillAnswers = emptyMap()
                                        currentStage = GeneratorStage.ACTIVE_TEST
                                    }
                                }
                            },
                            onDeleteSavedSet = { id ->
                                coroutineScope.launch { repository.deleteGeneratedTestSet(id) }
                            }
                        )
                    }
                }
            }
        }
    }
}

/**
 * Step 1: Legal Source Selection UI
 */
@OptIn(ExperimentalLayoutApi::class)
@Composable
private fun SourceSelectionContent(
    allCodes: List<LegalCode>,
    selectedCodeIds: Set<String>,
    selectedChapters: Map<String, Set<String>>,
    selectedArticleIds: Set<String>,
    searchQuery: String,
    onSearchChange: (String) -> Unit,
    selectedCategory: String,
    onCategorySelect: (String) -> Unit,
    expandedCodeId: String?,
    onToggleExpand: (String) -> Unit,
    onToggleCodeSelect: (String) -> Unit,
    onSelectAll: () -> Unit,
    onDeselectAll: () -> Unit,
    onToggleChapterSelect: (codeId: String, chapterTitle: String) -> Unit,
    onToggleArticleSelect: (articleId: String) -> Unit,
    resolvedArticleCount: Int,
    onNextConfig: () -> Unit
) {
    val categories = remember {
        listOf("Barchasi", "Xususiy huquq", "Protsessual huquq", "Jinoiy huquq", "Ommaviy huquq", "Ijtimoiy huquq", "Iqtisodiy huquq")
    }

    val filteredCodes = remember(allCodes, searchQuery, selectedCategory) {
        allCodes.filter { code ->
            val matchCategory = selectedCategory == "Barchasi" || code.category.equals(selectedCategory, ignoreCase = true)
            val matchQuery = searchQuery.isBlank() ||
                    code.shortName.contains(searchQuery, ignoreCase = true) ||
                    code.officialUzbekName.contains(searchQuery, ignoreCase = true)
            matchCategory && matchQuery
        }
    }

    LazyColumn(
        modifier = Modifier.fillMaxSize(),
        contentPadding = PaddingValues(16.dp),
        verticalArrangement = Arrangement.spacedBy(14.dp)
    ) {
        // Hero selection summary card
        item {
            Card(
                shape = RoundedCornerShape(16.dp),
                colors = CardDefaults.cardColors(containerColor = UzLegalNavyHeadings),
                elevation = CardDefaults.cardElevation(defaultElevation = 2.dp),
                modifier = Modifier.fillMaxWidth()
            ) {
                Column(modifier = Modifier.padding(18.dp)) {
                    Row(
                        modifier = Modifier.fillMaxWidth(),
                        horizontalArrangement = Arrangement.SpaceBetween,
                        verticalAlignment = Alignment.CenterVertically
                    ) {
                        Row(verticalAlignment = Alignment.CenterVertically) {
                            Icon(imageVector = Icons.Default.Gavel, contentDescription = null, tint = UzLegalTeal, modifier = Modifier.size(22.dp))
                            Spacer(modifier = Modifier.width(8.dp))
                            Text(
                                text = "Manbalar Baza Qamrovi",
                                style = MaterialTheme.typography.titleMedium.copy(fontWeight = FontWeight.Bold, color = Color.White)
                            )
                        }

                        Surface(
                            color = UzLegalTeal,
                            shape = RoundedCornerShape(12.dp)
                        ) {
                            Text(
                                text = "$resolvedArticleCount ta modda",
                                style = MaterialTheme.typography.labelMedium.copy(fontWeight = FontWeight.Bold, color = Color.White),
                                modifier = Modifier.padding(horizontal = 10.dp, vertical = 4.dp)
                            )
                        }
                    }

                    Spacer(modifier = Modifier.height(10.dp))

                    Text(
                        text = "Aynan tanlangan kodekslar va moddalardan o'zgasi test generatsiyasiga aralashmaydi.",
                        style = MaterialTheme.typography.bodySmall.copy(color = Color.White.copy(alpha = 0.8f), lineHeight = 16.sp)
                    )

                    Spacer(modifier = Modifier.height(12.dp))

                    Row(
                        modifier = Modifier.fillMaxWidth(),
                        horizontalArrangement = Arrangement.spacedBy(10.dp)
                    ) {
                        OutlinedButton(
                            onClick = onSelectAll,
                            colors = ButtonDefaults.outlinedButtonColors(contentColor = Color.White),
                            border = androidx.compose.foundation.BorderStroke(1.dp, Color.White.copy(alpha = 0.5f)),
                            shape = RoundedCornerShape(10.dp),
                            modifier = Modifier.weight(1f)
                        ) {
                            Text("Barcha 19 ta Kodeks", fontSize = 12.sp)
                        }

                        OutlinedButton(
                            onClick = onDeselectAll,
                            colors = ButtonDefaults.outlinedButtonColors(contentColor = UzLegalError),
                            border = androidx.compose.foundation.BorderStroke(1.dp, UzLegalError.copy(alpha = 0.5f)),
                            shape = RoundedCornerShape(10.dp),
                            modifier = Modifier.weight(1f)
                        ) {
                            Text("Tozalash", fontSize = 12.sp)
                        }
                    }
                }
            }
        }

        // Search and Filter Bar
        item {
            OutlinedTextField(
                value = searchQuery,
                onValueChange = onSearchChange,
                placeholder = { Text("Kodeks yoki modda nomini izlash...") },
                leadingIcon = { Icon(imageVector = Icons.Default.Search, contentDescription = null) },
                trailingIcon = {
                    if (searchQuery.isNotEmpty()) {
                        IconButton(onClick = { onSearchChange("") }) {
                            Icon(imageVector = Icons.Default.Clear, contentDescription = null)
                        }
                    }
                },
                singleLine = true,
                shape = RoundedCornerShape(12.dp),
                colors = OutlinedTextFieldDefaults.colors(
                    focusedBorderColor = UzLegalTeal,
                    unfocusedBorderColor = UzLegalBorder
                ),
                modifier = Modifier.fillMaxWidth()
            )
        }

        // Category Filter Chips
        item {
            FlowRow(
                modifier = Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.spacedBy(6.dp),
                verticalArrangement = Arrangement.spacedBy(6.dp)
            ) {
                categories.forEach { cat ->
                    val isSelected = selectedCategory == cat
                    FilterChip(
                        selected = isSelected,
                        onClick = { onCategorySelect(cat) },
                        label = { Text(cat, fontSize = 11.5.sp) },
                        colors = FilterChipDefaults.filterChipColors(
                            selectedContainerColor = UzLegalTeal,
                            selectedLabelColor = Color.White
                        )
                    )
                }
            }
        }

        // 19 Codes Expandable List
        items(filteredCodes) { code ->
            val isCodeSelected = selectedCodeIds.contains(code.id)
            val isExpanded = expandedCodeId == code.id
            val codeArticles = remember(code.id) { LegislationData.getArticlesForCode(code.id) }
            val codeChapters = remember(codeArticles) { codeArticles.map { it.chapter }.distinct() }

            Card(
                shape = RoundedCornerShape(14.dp),
                colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surface),
                border = androidx.compose.foundation.BorderStroke(
                    1.2.dp,
                    if (isCodeSelected) UzLegalTeal else UzLegalBorder
                ),
                modifier = Modifier.fillMaxWidth()
            ) {
