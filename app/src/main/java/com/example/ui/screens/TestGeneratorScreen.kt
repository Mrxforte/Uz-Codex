                Text("Topshirilgan testlar tarixi yo'q.", style = MaterialTheme.typography.bodyMedium.copy(color = UzLegalSlateBody))
            }
        } else {
            items(attempts) { att ->
                Card(
                    shape = RoundedCornerShape(12.dp),
                    colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surface),
                    border = androidx.compose.foundation.BorderStroke(1.dp, UzLegalBorder),
                    modifier = Modifier.fillMaxWidth()
                ) {
                    Row(
                        modifier = Modifier.padding(14.dp),
                        horizontalArrangement = Arrangement.SpaceBetween,
                        verticalAlignment = Alignment.CenterVertically
                    ) {
                        Column {
                            Text(att.testTitle, style = MaterialTheme.typography.bodyMedium.copy(fontWeight = FontWeight.Bold, color = UzLegalNavyHeadings))
                            Text("${att.correctCount} / ${att.totalCount} to'g'ri tapildi (+${att.earnedXp} XP)", style = MaterialTheme.typography.bodySmall.copy(color = UzLegalSlateBody))
                        }

                        Surface(
                            color = if (att.scorePercentage >= 70) UzLegalSuccessContainer else UzLegalErrorContainer,
                            shape = RoundedCornerShape(10.dp)
                        ) {
                            Text(
                                text = "${att.scorePercentage}%",
                                style = MaterialTheme.typography.labelMedium.copy(fontWeight = FontWeight.Bold, color = if (att.scorePercentage >= 70) UzLegalSuccess else UzLegalError),
                                modifier = Modifier.padding(horizontal = 10.dp, vertical = 4.dp)
                            )
                        }
                    }
                }
            }
        }
    }
