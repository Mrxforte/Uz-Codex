    ) {
        item {
            Text("Saqlangan RAG Test To'plamlari", style = MaterialTheme.typography.titleSmall.copy(fontWeight = FontWeight.Bold, color = UzLegalNavyHeadings))
        }

        if (savedSets.isEmpty()) {
            item {
                Text("Hozircha saqlangan RAG testlar mavjud emas.", style = MaterialTheme.typography.bodyMedium.copy(color = UzLegalSlateBody))
            }
        } else {
            items(savedSets) { set ->
                Card(
                    shape = RoundedCornerShape(12.dp),
                    colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surface),
                    border = androidx.compose.foundation.BorderStroke(1.dp, UzLegalBorder),
                    modifier = Modifier.fillMaxWidth()
                ) {
                    Row(
                        modifier = Modifier.padding(14.dp),
                        horizontalArrangement = Arrangement.SpaceBetween,
                        verticalAlignment = Alignment.CenterVertically
                    ) {
                        Column(modifier = Modifier.weight(1f)) {
                            Text(set.title, style = MaterialTheme.typography.titleSmall.copy(fontWeight = FontWeight.Bold, color = UzLegalNavyHeadings))
                            Text("${set.questionCount} ta savol • ${set.selectionSummary}", style = MaterialTheme.typography.bodySmall.copy(color = UzLegalSlateBody))
                        }

                        Row {
                            IconButton(onClick = { onLaunchSavedSet(set) }) {
                                Icon(imageVector = Icons.Default.PlayArrow, contentDescription = null, tint = UzLegalTeal)
                            }
                            IconButton(onClick = { onDeleteSavedSet(set.id) }) {
                                Icon(imageVector = Icons.Default.Delete, contentDescription = null, tint = UzLegalError)
                            }
