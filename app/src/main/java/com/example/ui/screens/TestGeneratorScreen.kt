                shape = RoundedCornerShape(14.dp),
                colors = CardDefaults.cardColors(containerColor = UzLegalTealSurface),
                border = androidx.compose.foundation.BorderStroke(1.dp, UzLegalTealBorder),
                modifier = Modifier.fillMaxWidth()
            ) {
                Column(modifier = Modifier.padding(14.dp)) {
                    Row(verticalAlignment = Alignment.CenterVertically) {
                        Icon(imageVector = Icons.Default.MenuBook, contentDescription = null, tint = UzLegalTeal, modifier = Modifier.size(18.dp))
                        Spacer(modifier = Modifier.width(6.dp))
                        Text(
                            text = "Manba: ${question.codeName}, ${question.articleNumberStr} (${question.articleTitle})",
                            style = MaterialTheme.typography.labelMedium.copy(fontWeight = FontWeight.Bold, color = UzLegalTealDark)
                        )
                    }

                    if (showAnswerImmediately && isConfirmedPractice) {
                        Spacer(modifier = Modifier.height(8.dp))
                        Text(text = "Rasmiy Modda Iqtibosi:\n\"${question.supportingSourceExcerpt}\"", style = MaterialTheme.typography.bodySmall.copy(color = UzLegalNavyHeadings, lineHeight = 17.sp))
                        Spacer(modifier = Modifier.height(8.dp))
                        Text(text = "Huquqiy Izoh:\n${question.explanation}", style = MaterialTheme.typography.bodySmall.copy(color = UzLegalSlateBody))
                    }
                }
            }
        }

        // Bottom Action Buttons
        item {
            Row(
                modifier = Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.spacedBy(10.dp)
            ) {
                if (currentIndex > 0) {
                    OutlinedButton(
                        onClick = onPrev,
                        shape = RoundedCornerShape(12.dp),
                        modifier = Modifier
                            .weight(1f)
                            .height(48.dp)
                    ) {
                        Text("Oldingi")
                    }
                }

                if (showAnswerImmediately && !isConfirmedPractice) {
                    Button(
                        onClick = onConfirmPractice,
                        colors = ButtonDefaults.buttonColors(containerColor = UzLegalNavyHeadings),
                        shape = RoundedCornerShape(12.dp),
                        modifier = Modifier
                            .weight(1f)
                            .height(48.dp)
                    ) {
                        Text("Tekshirish")
                    }
                }

                val isLast = currentIndex == totalCount - 1
                Button(
                    onClick = { if (isLast) onFinish() else onNext() },
                    colors = ButtonDefaults.buttonColors(containerColor = if (isLast) UzLegalNavyHeadings else UzLegalTeal),
                    shape = RoundedCornerShape(12.dp),
                    modifier = Modifier
                        .weight(1f)
                        .height(48.dp)
                ) {
                    Text(if (isLast) "Testni yakunlash" else "Keyingi")
                }
            }
        }
    }
}

/**
 * Step 5: Test Results Screen
 */
@Composable
private fun TestResultsContent(
    questions: List<GeneratedTestQuestion>,
    userSingleAnswers: Map<Int, Int>,
    onRetake: () -> Unit,
    onNewTest: () -> Unit
) {
    val total = questions.size
    val correct = remember(questions, userSingleAnswers) {
        questions.filterIndexed { idx, q ->
            userSingleAnswers[idx]?.let { q.correctIndices.contains(it) } == true
        }.size
    }
    val scorePct = if (total > 0) (correct * 100) / total else 0

    LazyColumn(
        modifier = Modifier.fillMaxSize(),
        contentPadding = PaddingValues(16.dp),
        verticalArrangement = Arrangement.spacedBy(16.dp)
    ) {
        item {
            Card(
                shape = RoundedCornerShape(20.dp),
                colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surface),
                border = androidx.compose.foundation.BorderStroke(1.dp, UzLegalBorder),
                modifier = Modifier.fillMaxWidth()
            ) {
                Column(
                    modifier = Modifier.padding(24.dp),
                    horizontalAlignment = Alignment.CenterHorizontally
                ) {
                    Box(
                        modifier = Modifier
                            .size(110.dp)
                            .clip(CircleShape)
                            .background(if (scorePct >= 70) UzLegalSuccessContainer else UzLegalErrorContainer),
                        contentAlignment = Alignment.Center
                    ) {
                        Column(horizontalAlignment = Alignment.CenterHorizontally) {
                            Text("$scorePct%", style = MaterialTheme.typography.headlineMedium.copy(fontWeight = FontWeight.Bold, color = if (scorePct >= 70) UzLegalSuccess else UzLegalError))
                            Text("$correct / $total", style = MaterialTheme.typography.labelSmall.copy(color = UzLegalSlateBody))
                        }
                    }

                    Spacer(modifier = Modifier.height(16.dp))
                    Text("Natija Yakunlandi", style = MaterialTheme.typography.titleMedium.copy(fontWeight = FontWeight.Bold, color = UzLegalNavyHeadings))
                }
            }
        }

        item {
            Row(
                modifier = Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.spacedBy(10.dp)
            ) {
                OutlinedButton(
                    onClick = onNewTest,
                    shape = RoundedCornerShape(12.dp),
                    modifier = Modifier
                        .weight(1f)
                        .height(48.dp)
                ) {
                    Text("Yangi Manba")
                }

                Button(
                    onClick = onRetake,
                    colors = ButtonDefaults.buttonColors(containerColor = UzLegalTeal),
                    shape = RoundedCornerShape(12.dp),
                    modifier = Modifier
                        .weight(1f)
                        .height(48.dp)
                ) {
                    Text("Qayta Topshirish")
                }
            }
        }
    }
}

/**
