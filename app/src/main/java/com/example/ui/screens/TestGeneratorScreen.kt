 */
@Composable
private fun SavedHistoryContent(
    savedSets: List<GeneratedTestSetEntity>,
    attempts: List<TestAttemptHistoryEntity>,
    onLaunchSavedSet: (GeneratedTestSetEntity) -> Unit,
    onDeleteSavedSet: (String) -> Unit
) {
    LazyColumn(
        modifier = Modifier.fillMaxSize(),
        contentPadding = PaddingValues(16.dp),
